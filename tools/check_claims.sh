#!/bin/sh
# Claim traceability check. Modes: (default) check + summary; --md prints CLAIMS.md.
# Rules: every dep must exist; verified/derived claims may depend only on axioms and verified/derived claims (no cycles);
# every verified or refuted claim must have evidence that exits 0 NOW.
MODE=check; [ "$1" = "--md" ] && MODE=md
awk -F'\t' -v mode="$MODE" '
function walk(id,d,  n,a,i,x){ if(d>40){cyc=1;return} onst[id]=1; n=split(deps[id],a,","); for(i=1;i<=n;i++){ x=a[i]; if(x=="") continue
    if(onst[x]){ cyc=1; cycn=cycn " " id "->" x; continue }
    if(!(x in type)){ undef=undef " " id "->" x; continue }
    if(type[x]=="axiom"){ ax[x]=1; continue }
    if(status[x]!="verified"&&status[x]!="derived"){ badd=badd " " id "->" x; continue }
    if(!(x in seen)){ seen[x]=1; der[x]=1; walk(x,d+1) } }
  onst[id]=0 }
function keys(arr,  k,s){ s=""; for(k in arr) s=s (s==""?"":",") k; return s }
/^#/ || NF<6 { next }
{ n++; id[n]=$1; type[$1]=$2; status[$1]=$3; strength[$1]=$4; deps[$1]=$5; claim[$1]=$6; cmd[$1]=$7 }
END{
  for(i=1;i<=n;i++){ c=id[i]; delete seen; delete ax; delete der; if(status[c]=="verified"||status[c]=="derived"||status[c]=="refuted"){ if(status[c]!="refuted"){ walk(c,0) } }
    roots[c]=keys(ax); dd[c]=keys(der)
    ev="n/a"; if(cmd[c]!=""&&(status[c]=="verified"||status[c]=="refuted")){ r=system("(" cmd[c] ") >/dev/null 2>&1"); ev=(r==0)?"PASS":"FAIL"; if(r!=0) failing++ }
    else if(status[c]=="verified"){ ev="MISSING"; failing++ }
    evid[c]=ev; cnt[status[c]]++ }
  dagok=(undef==""&&badd==""&&!cyc)
  if(mode=="md"){
    print "# Claim register (generated by tools/check_claims.sh from claims.tsv)\n"
    print "Every claim lists the axioms it ultimately rests on. Strength says how the evidence supports it; `trusted` axioms are assumptions, not proven.\n"
    for(i=1;i<=n;i++){ c=id[i]; printf "- **%s** [%s, %s, evidence: %s, strength: %s] %s", c,type[c],status[c],evid[c],strength[c],claim[c]
      if(roots[c]!="") printf " Rests on axioms: %s.",roots[c]; if(dd[c]!="") printf " Via claims: %s.",dd[c]; printf "\n" }
    exit 0 }
  for(i=1;i<=n;i++){ c=id[i]; printf "CLAIM %s status=%s evidence=%s roots=%s via=%s\n",c,status[c],evid[c],roots[c],dd[c] }
  printf "CLAIMS verified=%d refuted=%d unverified=%d not_claimed=%d not_implemented=%d axioms=%d evidence_failing=%d dag_ok=%s\n",cnt["verified"]+0,cnt["refuted"]+0,cnt["unverified"]+0,cnt["not_claimed"]+0,cnt["not_implemented"]+0,cnt["axiom"]+0,failing+0,dagok?"true":"false"
  if(!dagok){ print "DAG PROBLEMS undefined:" undef " non-verified-deps:" badd " cycle:" cycn }
  exit ((failing+0)>0||!dagok)
}' claims.tsv
